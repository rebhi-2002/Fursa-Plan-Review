const dictionaries: Record<Language, TranslationDictionary> = { ar, en };

interface LanguageState {
  lang: Language;
  setLang: (lang: Language) => void;
}

const getInitialLanguage = (): Language => {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("fursa-lang") as Language;
    if (saved === "ar" || saved === "en") return saved;
  }
  return "ar";
};

export const useLanguageStore = create<LanguageState>((set) => ({
  lang: getInitialLanguage(),
  setLang: (lang) => {
    if (typeof window !== "undefined") {
      localStorage.setItem("fursa-lang", lang);
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    }
    set({ lang });
  },
}));

function interpolate(
  template: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) =>
    vars[key] !== undefined ? String(vars[key]) : `{${key}}`,
  );
}

export function useT() {
  const lang = useLanguageStore((state) => state.lang);

  return function t(
    key: string,
    varsOrDefault?: Record<string, string | number> | string,
    maybeDefault?: string,
  ): string {
    let vars: Record<string, string | number> | undefined;
    let defaultText: string | undefined;
    if (typeof varsOrDefault === "string") {
      defaultText = varsOrDefault;
    } else {
      vars = varsOrDefault;
      defaultText = maybeDefault;
    }
    const template =
      dictionaries[lang]?.[key] ?? dictionaries.ar[key] ?? defaultText ?? key;
    return interpolate(template, vars);
  };
}

export function LangProvider({ children }: { children: React.ReactNode }) {
  const lang = useLanguageStore((state) => state.lang);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  return <>{children}</>;
}
